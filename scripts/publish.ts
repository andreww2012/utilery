import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const MAIN_BRANCH = 'main';

const ROOT = path.resolve(import.meta.dirname, '..');
const THIRD_PARTY_NOTICES_PATH = path.join(ROOT, 'THIRD_PARTY_NOTICES.md');

const getCurrentBranch = () => {
  const {GITHUB_REF_NAME: githubRefNameEnv} = process.env;
  if (githubRefNameEnv) {
    return githubRefNameEnv;
  }

  // eslint-disable-next-line sonar/no-os-command-from-path -- `git` is part of the trusted CI/dev toolchain, resolved from a trusted PATH.
  return execFileSync('git', ['rev-parse', '--abbrev-ref', 'HEAD'], {
    cwd: ROOT,
    encoding: 'utf8',
  }).trim();
};

const run = () => {
  const currentBranch = getCurrentBranch();

  if (currentBranch !== MAIN_BRANCH) {
    throw new Error(
      `Refusing to publish from "${currentBranch}": releases are only allowed from "${MAIN_BRANCH}".`,
    );
  }

  // The notices table is (re)generated by `prepublishOnly` on every publish, so the working tree
  // must get the original file back afterward
  const originalNoticesText = fs.readFileSync(THIRD_PARTY_NOTICES_PATH, 'utf8');

  try {
    // eslint-disable-next-line sonar/no-os-command-from-path -- `pnpm` is the pinned CI/dev toolchain, resolved from a trusted PATH.
    execFileSync('pnpm', ['exec', 'changeset', 'publish'], {stdio: 'inherit'});
  } finally {
    fs.writeFileSync(THIRD_PARTY_NOTICES_PATH, originalNoticesText);
  }
};

run();
